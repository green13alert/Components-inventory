/**
 * Compile the authoritative sketches with Arduino CLI on PATH.
 * Pins the board cores and libraries. Exits non-zero when a compile fails.
 * Does not record a hardware test.
 */
import { spawnSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const CORES = [
  { id: 'arduino:avr', version: '1.8.7' },
  { id: 'esp32:esp32', version: '3.3.12' },
]

const LIBRARIES = [
  { name: 'Adafruit BME280 Library', version: '2.3.0' },
  { name: 'Adafruit Unified Sensor', version: '1.1.15' },
  { name: 'Adafruit BusIO', version: '1.17.4' },
  { name: 'Servo', version: '1.3.0' },
  { name: 'MD_MAX72XX', version: '3.5.1' },
]

const SKETCHES = [
  {
    slug: '8',
    folder: 'motion-sensor-alarm',
    fqbn: 'arduino:avr:uno',
    board: 'Arduino Uno R3',
  },
  {
    slug: '18',
    folder: 'servo-pan-tilt-camera',
    fqbn: 'arduino:avr:uno',
    board: 'Arduino Uno R3',
  },
  {
    slug: '23',
    folder: 'esp32-wifi-weather-station',
    fqbn: 'esp32:esp32:esp32',
    board: 'ESP32 Dev Module (ESP32-DevKitC V4)',
  },
  {
    slug: '25',
    folder: 'led-matrix-maze',
    fqbn: 'arduino:avr:uno',
    board: 'Arduino Uno R3',
  },
  {
    slug: '24',
    folder: 'esp32-ble-rgb-controller',
    fqbn: 'esp32:esp32:esp32',
    board: 'ESP32 Dev Module (ESP32-DevKitC V4)',
  },
]

function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, encoding: 'utf8', shell: false })
  const output = `${result.stdout ?? ''}${result.stderr ?? ''}`
  if (output.trim()) {
    process.stdout.write(output.endsWith('\n') ? output : `${output}\n`)
  }
  if (result.error) {
    console.error(result.error.message)
    process.exit(1)
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1)
  }
  return output
}

function cli() {
  const found = spawnSync('arduino-cli', ['version'], { encoding: 'utf8' })
  if (found.status !== 0) {
    console.error('arduino-cli is not on PATH. Install Arduino CLI 1.5.1 and retry. This script does not use a machine-specific path.')
    process.exit(1)
  }
  return 'arduino-cli'
}

function sketches() {
  const extracted = spawnSync(
    process.execPath,
    [
      '--experimental-strip-types',
      '--input-type=module',
      '--eval',
      `
import { MOTION_SENSOR_ALARM_FIRMWARE } from './constants/walkthroughs/motion-sensor-alarm.ts'
import { SERVO_PAN_TILT_CAMERA_FIRMWARE } from './constants/walkthroughs/servo-pan-tilt-camera.ts'
import { ESP32_WIFI_WEATHER_FIRMWARE } from './constants/firmware/esp32-wifi-weather-station.ts'
import { ESP32_BLE_RGB_FIRMWARE } from './constants/firmware/esp32-ble-rgb-controller.ts'
import { LED_MATRIX_MAZE_FIRMWARE } from './constants/firmware/led-matrix-maze.ts'
import { sketchChecksum } from './lib/sketch-checksum.ts'
const rows = [
  ['8', MOTION_SENSOR_ALARM_FIRMWARE],
  ['18', SERVO_PAN_TILT_CAMERA_FIRMWARE],
  ['23', ESP32_WIFI_WEATHER_FIRMWARE],
  ['24', ESP32_BLE_RGB_FIRMWARE],
  ['25', LED_MATRIX_MAZE_FIRMWARE],
]
process.stdout.write(JSON.stringify(Object.fromEntries(rows.map(([slug, source]) => [slug, { source, checksum: sketchChecksum(source) }]))))
`,
    ],
    { cwd: root, encoding: 'utf8' },
  )
  if (extracted.status !== 0) {
    process.stderr.write(extracted.stderr ?? '')
    process.exit(extracted.status ?? 1)
  }
  return JSON.parse(extracted.stdout)
}

const arduino = cli()
const versionLine = run(arduino, ['version']).trim().split('\n')[0]
for (const core of CORES) {
  run(arduino, ['core', 'install', `${core.id}@${core.version}`])
}
for (const library of LIBRARIES) {
  run(arduino, ['lib', 'install', `${library.name}@${library.version}`])
}

const sources = sketches()
const compiled = []
const workspace = mkdtempSync(join(tmpdir(), 'solderi-firmware-'))
try {
  for (const sketch of SKETCHES) {
    const source = sources[sketch.slug]
    const folder = join(workspace, sketch.folder)
    mkdirSync(folder, { recursive: true })
    writeFileSync(join(folder, `${sketch.folder}.ino`), source.source, 'utf8')
    console.log(`\nCompiling project ${sketch.slug} for ${sketch.fqbn}`)
    run(arduino, ['compile', '--fqbn', sketch.fqbn, '--warnings', 'all', folder])
    compiled.push({
      slug: sketch.slug,
      fqbn: sketch.fqbn,
      board: sketch.board,
      checksum: source.checksum,
      result: 'passed',
    })
  }
} finally {
  rmSync(workspace, { recursive: true, force: true })
}

const record = `/** Generated by npm run firmware:compile. A checksum match means that sketch compiled. It is not a hardware test. */
export const FIRMWARE_COMPILE_RECORD = {
  arduinoCli: ${JSON.stringify(versionLine)},
  cores: ${JSON.stringify(Object.fromEntries(CORES.map((core) => [core.id, core.version])), null, 2)},
  libraries: ${JSON.stringify(Object.fromEntries(LIBRARIES.map((library) => [library.name, library.version])), null, 2)},
  sketches: ${JSON.stringify(Object.fromEntries(compiled.map((item) => [item.slug, { fqbn: item.fqbn, board: item.board, checksum: item.checksum, result: item.result }])), null, 2)},
} as const
`
mkdirSync(join(root, 'firmware'), { recursive: true })
writeFileSync(join(root, 'firmware', 'compile-record.ts'), record, 'utf8')
console.log('Wrote firmware/compile-record.ts')
